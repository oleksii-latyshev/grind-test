HEADER = """/**
 * {name} interface strings.
 *
 * Chrome only: study notes, questions, explanations and hints stay Ukrainian whatever this
 * is set to, because that is the language of the exam. See `src/i18n/index.tsx`.
 */
{decl}
"""

NAMES = {"uk": "Ukrainian", "ru": "Russian", "en": "English"}


def escape(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def emit(locale, index):
    lines = []
    for entry in M:
        lines.append(f'  "{entry[0]}": "{escape(entry[index])}",')
    body = "\n".join(lines)
    if locale == "en":
        decl = f"export const en = {{\n{body}\n}};\n\n/** Every catalogue carries exactly these ids. */\nexport type MessageId = keyof typeof en;"
    else:
        decl = (
            f'import type {{ MessageId }} from "./en";\n\n'
            f"export const {locale}: Record<MessageId, string> = {{\n{body}\n}};"
        )
    return HEADER.format(name=NAMES[locale], decl=decl)


if __name__ == "__main__":
    out = pathlib.Path("src/i18n/messages")
    out.mkdir(parents=True, exist_ok=True)
    for locale, index in (("en", 3), ("uk", 1), ("ru", 2)):
        (out / f"{locale}.ts").write_text(emit(locale, index))
    ids = [entry[0] for entry in M]
    assert len(ids) == len(set(ids)), "duplicate message id"
    print(f"{len(M)} messages × 3 locales")
